function stripSvgDimensions(svg) {
  return svg
    .replace(/<\?xml[^?]*\?>\s*/i, "")
    .trim()
    .replace(/\swidth="[^"]*"/i, "")
    .replace(/\sheight="[^"]*"/i, "");
}

function normalizeMonochromeSvg(svg) {
  return svg
    .replace(/fill="(?!none|currentColor)[^"]*"/gi, 'fill="currentColor"')
    .replace(/stroke="(?!none|currentColor)[^"]*"/gi, 'stroke="currentColor"');
}

function readSvg(relativePath, { monochrome = false } = {}) {
  const absolutePath = join(portalRoot, "public", relativePath);
  const raw = readFileSync(absolutePath, "utf8");
  const stripped = stripSvgDimensions(raw);
  return monochrome ? normalizeMonochromeSvg(stripped) : stripped;
}

function serializeRecord(record) {
  return Object.entries(record)
    .map(([key, value]) => {
      if (typeof value === "string") {
        return `  ${key}: ${JSON.stringify(value)},`;
      }
      const nested = Object.entries(value)
        .map(([variant, markup]) => `    ${variant}: ${JSON.stringify(markup)},`)
        .join("\n");
      return `  ${key}: {\n${nested}\n  },`;
    })
    .join("\n");
}

